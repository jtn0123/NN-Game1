"""Generate the C# simulation's static cave data from the authoritative Python caves.

The C# engine never re-implements layout repairs or polish edits: it receives
the exact final layouts that the Python session plays.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .classic_secrets import SITES
from .mine import ENTRANCES, MINE_SPEC, TORCHES
from .session import CaveSession

DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "unity/Assets/Sim/Generated/CaveData.g.cs"
LAYOUT_CHARACTERS = frozenset(".#*EDdsSA$pgzOMF^~=HPtv")


def _literal(text: str) -> str:
    if any(ch in text for ch in '"\\') or any(ord(ch) < 32 or ord(ch) > 126 for ch in text):
        raise ValueError(f"cannot embed text in C#: {text!r}")
    return f'"{text}"'


def _spec(name: str, layout: tuple[str, ...], indent: str) -> str:
    unknown = set("".join(layout)) - LAYOUT_CHARACTERS
    if unknown:
        raise ValueError(f"{name} uses unknown layout characters {sorted(unknown)}")
    rows = f",\n{indent}    ".join(_literal(row) for row in layout)
    return f"new CaveSpec({_literal(name)}, new[]\n{indent}{{\n{indent}    {rows},\n{indent}}})"


def _tiles(tiles: tuple[tuple[int, int], ...]) -> str:
    return ", ".join(f"({col}, {row})" for col, row in tiles)


def source() -> str:
    caves = CaveSession(level=0).cave_game.CAVES
    indent = "            "
    specs = f",\n{indent}".join(_spec(cave.name, cave.layout, indent) for cave in caves)
    secrets = ",\n            ".join(
        f"new SecretSite({_literal(name)}, ({cache.block[0]}, {cache.block[1]}), "
        f"({cache.crystal[0]}, {cache.crystal[1]}))"
        for name, caches in sorted(SITES.items())
        for cache in caches
    )
    return f"""// <auto-generated>
// Generated by `python -m src.unity_bridge.export_sim_data` from the Python caves.
// Do not edit by hand; tests/test_sim_trace.py fails when this file is stale.
// </auto-generated>
#nullable enable

namespace CrystalCaves.Sim
{{
    public static class CaveData
    {{
        public static readonly CaveSpec[] Caves =
        {{
            {specs},
        }};

        public static readonly CaveSpec Mine =
            {_spec(MINE_SPEC.name, MINE_SPEC.layout, "            ")};

        public static readonly SecretSite[] Secrets =
        {{
            {secrets},
        }};

        public static readonly (int Col, int Row)[] MineEntrances =
        {{
            {_tiles(ENTRANCES)},
        }};

        public static readonly (int Col, int Row)[] MineTorches =
        {{
            {_tiles(TORCHES)},
        }};
    }}
}}
"""


def write(output: Path = DEFAULT_OUTPUT) -> Path:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source(), encoding="utf-8")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    print(f"Wrote {write(parser.parse_args().output)}")


if __name__ == "__main__":
    main()
